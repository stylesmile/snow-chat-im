package com.stylesmile.chat.entity;

import lombok.Data;

import java.util.Date;

/**
 * 会话实体类 - 存储用户之间的私聊或群聊会话信息
 *
 * 这个类表示一个聊天会话，包括：
 * - 一对一私聊会话（targetType = "friend"）
 * - 群聊会话（targetType = "group"）
 *
 * 每个会话包含：
 * - 会话的唯一标识符
 * - 参与者信息（用户ID和目标ID/类型）
 * - 最后一条消息的内容和时间
 * - 未读消息计数
 * - 免打扰设置
 * - 最后更新时间
 *
 * 数据库映射：
 * - 表名：chat_session
 * - 主键：id（自增）
 * - 唯一索引：uk_user_target(user_id, target_id, target_type)
 *
 * @author chenye
 * @date 2018/12/10
 * @version 1.0.0
 * @since 2024-01-01
 */
@Data
public class ChatSession {

    /**
     * 会话主键ID - 会话的唯一标识符
     *
     * 这个字段是数据库表的主键，自动生成。
     * 用于：
     * - 唯一标识每个会话
     * - 数据库关联查询
     * - 缓存键
     *
     * 数据库类型：INT (自增)
     * 约束：NOT NULL, AUTO_INCREMENT
     */
    private Long id;

    /**
     * 用户ID - 会话的所有者
     *
     * 这个字段标识哪个用户拥有这个会话。
     * 在私聊场景中：这是发送者或接收者的用户ID
     * 在群聊场景中：这是群组成员的用户ID
     *
     * 数据库类型：INT
     * 约束：NOT NULL
     * 索引：包含在uk_user_target唯一索引中
     *
     * 业务逻辑：
     * - 一个用户可以有多个会话
     * - 通过user_id可以快速查找用户的所有会话
     * - 用于分页查询用户的会话列表
     */
    private Long userId;

    /**
     * 目标ID - 会话的对方（好友ID或群组ID）
     *
     * 这个字段标识会话的另一方：
     * - 如果是私聊（targetType = "friend"）：这是好友的用户ID
     * - 如果是群聊（targetType = "group"）：这是群组的ID
     *
     * 数据库类型：INT
     * 约束：NOT NULL
     * 索引：包含在uk_user_target唯一索引中
     *
     * 业务规则：
     * - 私聊时：targetId是对方的用户ID
     * - 群聊时：targetId是群组ID
     * - 用于查找特定的会话
     */
    private Long targetId;

    /**
     * 目标类型 - 会话的类型（私聊或群聊）
     *
     * 这个字段定义会话的类型，决定如何处理消息：
     *
     * 支持的类型：
     * - "friend": 私聊会话
     *   - 消息只发送给指定的用户
     *   - 使用toUserId字段指定接收者
     *
     * - "group": 群聊会话
     *   - 消息广播给所有群组成员
     *   - 使用groupId字段指定群组
     *
     * 数据库类型：VARCHAR(20)
     * 约束：NOT NULL
     * 索引：包含在uk_user_target唯一索引中
     *
     * 使用场景：
     * - 区分私聊和群聊的消息处理逻辑
     * - 确定消息的投递方式
     * - 计算未读消息数
     */
    private String targetType;

    /**
     * 最后一条消息的内容 - 显示在会话列表中
     *
     * 这个字段存储会话中最后一条消息的内容摘要。
     * 用于在会话列表中预览消息内容。
     *
     * 数据库类型：TEXT
     * 约束：NULL
     *
     * 内容格式：
     * - 对于文本消息：直接存储消息文本
     * - 对于图片消息：存储"[图片]"
     * - 对于文件消息：存储"[文件]"
     * - 对于系统消息：存储系统提示文本
     *
     * 业务逻辑：
     * - 当发送新消息时，更新此字段
     * - 在会话列表中显示最后一条消息的预览
     * - 如果消息内容过长，可能被截断
     */
    private String lastMsg;

    /**
     * 最后一条消息的时间 - 用于会话列表排序
     *
     * 这个字段记录最后一条消息的发送时间。
     * 用于会话列表的排序和显示。
     *
     * 数据库类型：DATETIME
     * 约束：NULL
     * 默认值：NULL
     *
     * 业务逻辑：
     * - 用于按时间排序会话列表
     * - 显示最后一条消息的时间戳
     * - 如果会话没有消息，此字段为NULL
     *
     * 显示格式：
     * - 今天：显示时间（如"14:30"）
     * - 昨天：显示"昨天"
     * - 更早：显示日期（如"7/20"）
     */
    private java.util.Date lastMsgTime;

    /**
     * 未读消息数 - 显示在会话列表中的徽章
     *
     * 这个字段记录用户在这个会话中未读的消息数量。
     * 用于在会话列表中显示未读消息的徽章。
     *
     * 数据库类型：INT
     * 约束：NULL
     * 默认值：0
     *
     * 业务逻辑：
     * - 每收到一条新消息，计数加1
     * - 用户打开会话时，计数清零
     * - 显示为红色徽章（如果有未读消息）
     *
     * 性能优化：
     * - 使用缓存存储未读计数
     * - 定期同步到数据库
     * - 避免频繁更新数据库
     */
    private Integer unreadCount;
    /**
     * 创建时间
     */
    private Date createTime;

    /**
     * 是否免打扰 - 用户的静音设置
     *
     * 这个字段控制用户是否接收这个会话的消息通知。
     * 用户可以设置特定会话为免打扰模式。
     *
     * 数据库类型：INT
     * 约束：NULL
     * 默认值：0
     *
     * 值含义：
     * - 0: 关闭免打扰（默认）
     *   - 接收所有消息通知
     *   - 显示未读消息徽章
     *
     * - 1: 开启免打扰
     *   - 不接收消息通知
     *   - 仍显示未读消息计数
     *   - 消息仍然会被接收和存储
     *
     * 业务逻辑：
     * - 用户可以在设置中切换免打扰
     * - 免打扰不影响消息的接收和存储
     * - 只影响通知的显示
     */
    private Integer isMuted;

    /**
     * 更新时间 - 记录会话的最后修改时间
     *
     * 这个字段记录会话记录的最后更新时间。
     * 每次修改会话（发送消息、更新设置等）都会更新此字段。
     *
     * 数据库类型：DATETIME
     * 约束：NULL
     * 默认值：CURRENT_TIMESTAMP
     *
     * 业务逻辑：
     * - 用于审计和调试
     * - 可以用于清理过期会话
     * - 可以用于数据同步
     *
     * 注意：此字段与lastMsgTime不同
     * - lastMsgTime: 最后一条消息的时间
     * - updateTime: 会话记录的最后修改时间
     *
     * 更新时机：
     * - 发送新消息
     * - 修改免打扰设置
     * - 清除未读计数
     */
    private java.util.Date updateTime;

    /**
     * 无参构造函数 - MyBatis和Jackson需要
     *
     * 这个构造函数用于：
     * - MyBatis结果映射
     * - Jackson JSON反序列化
     * - 测试中的对象创建
     *
     * 注意：使用@Data注解会自动生成getter/setter
     */
    public ChatSession() {
    }
}
