/**
 * 消息召回DTO（Data Transfer Object）- 用于封装消息召回（撤回）的请求数据
 *
 * 这个类定义了客户端召回消息时需要提供的所有字段。
 * 消息召回是即时通讯系统的重要功能，用于：
 *
 * 1. 允许用户撤回错误发送的消息
 * 2. 保护用户隐私，删除敏感信息
 * 3. 纠正拼写错误或不当内容
 * 4. 满足合规要求（某些行业需要消息可追溯）
 *
 * 使用场景：
 * - 用户发送了错误的消息，需要撤回
 * - 用户发送了敏感信息，需要删除
 * - 管理员需要删除违规内容
 * - 系统需要自动删除过期消息
 *
 * @author Snow Chat Team
 * @version 1.0.0
 * @since 2024-01-01
 */
package com.stylesmile.chat.dto;

/**
 * Lombok注解库 - 自动生成getter、setter、toString、equals和hashCode方法
 *
 * @Data: 综合注解，包含以下功能：
 * - @Getter: 生成所有字段的getter方法
 * - @Setter: 生成所有字段的setter方法
 * - @ToString: 生成toString方法，便于调试
 * - @EqualsAndHashCode: 生成equals和hashCode方法，便于集合操作
 */
import lombok.Data;

/**
 * 消息召回DTO类
 *
 * 这个类封装了召回消息所需的信息。
 * 消息召回的处理流程：
 *
 * 1. 客户端发送召回请求
 * 2. 服务器验证用户身份和权限
 * 3. 服务器检查召回时间限制
 * 4. 服务器更新消息状态为已召回
 * 5. 服务器通知所有接收者消息已被召回
 * 6. 服务器从缓存和搜索索引中删除消息
 *
 * 召回时间限制：
 * - 私聊消息：发送后2分钟内可以召回
 * - 群聊消息：发送后2分钟内可以召回
 * - 超过时间限制后，召回请求会被拒绝
 *
 * 权限规则：
 * - 只能召回自己发送的消息
 * - 群主或管理员可以召回任何人的消息（可配置）
 * - 系统消息不能被召回
 *
 * 设计考虑：
 * - 使用软删除，保留召回记录用于审计
 * - 通知所有接收者消息已被召回
 * - 保留消息的元数据（发送时间、发送者等）
 *
 * @author Snow Chat Team
 * @version 1.0.0
 * @since 2024-01-01
 */
@Data
public class RecallMessageDTO {

    /**
     * 用户ID - 发起召回操作的用户
     *
     * 这个字段标识哪个用户要召回消息。
     * 系统会验证这个用户是否有权限召回指定的消息。
     *
     * 业务规则：
     * - 用户只能召回自己发送的消息
     * - 群主或管理员可以召回任何人的消息（可配置）
     * - 系统消息不能被任何用户召回
     *
     * 验证逻辑：
     * 1. 检查用户是否存在
     * 2. 检查用户是否是消息的发送者
     * 3. 检查用户是否有管理员权限（如果召回他人的消息）
     * 4. 检查消息是否可以被召回（未被召回、在时间限制内）
     *
     * 数据库映射：对应chat_message表的sender_id字段
     * 约束：不能为null，必须是有效的用户ID
     *
     * 安全考虑：
     * - 验证用户身份，防止伪造召回请求
     * - 记录召回操作的日志，便于审计
     * - 限制召回频率，防止滥用
     *
     * 示例：
     * ```java
     * RecallMessageDTO dto = new RecallMessageDTO();
     * dto.setUserId(1001L); // 发送者要召回自己的消息
     * dto.setMessageId(5001L);
     * ```
     */
    private Long userId;

    /**
     * 消息ID - 被召回的消息
     *
     * 这个字段标识要召回的具体消息。
     * 系统会验证这条消息是否可以被召回。
     *
     * 召回条件（必须全部满足）：
     * 1. 消息存在且未被召回
     * 2. 消息在召回时间限制内（2分钟）
     * 3. 用户是消息的发送者或具有管理员权限
     * 4. 消息类型不是系统消息
     *
     * 数据库映射：对应chat_message表的id字段
     * 约束：不能为null，必须是有效的消息ID
     *
     * 处理逻辑：
     * 1. 查询消息是否存在
     * 2. 检查消息的发送时间
     * 3. 计算是否在召回时间限制内
     * 4. 更新消息的is_recalled字段为true
     * 5. 保留原始消息内容用于审计
     * 6. 通知所有接收者消息已被召回
     *
     * 状态变更：
     * - 召回前：消息状态为NORMAL
     * - 召回后：消息状态为RECALLED
     * - 显示：在客户端显示"[消息已召回]"占位符
     *
     * 性能优化：
     * - 使用索引加速消息查询
     * - 使用缓存存储最近召回的消息
     * - 异步通知接收者，不阻塞主流程
     *
     * 示例：
     * ```java
     * RecallMessageDTO dto = new RecallMessageDTO();
     * dto.setUserId(1001L);
     * dto.setMessageId(5001L); // 召回ID为5001的消息
     * ```
     */
    private Long messageId;
}
